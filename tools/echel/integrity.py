REPORT_PATH = "reports/repository-integrity-audit.md"


@dataclass(frozen=True)
class IntegrityFinding:
    finding_id: str
    severity: str
    area: str
    source: str
    impact: str
    required_action: str
    owner: str
    status: str = "Open"


